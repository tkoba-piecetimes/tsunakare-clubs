def get(path):
    return OVERRIDES.get(path)


def apply_body(body, ov):
    """Replace the first H1 text and/or insert lead paragraphs right after the H1 block."""
    if ov.get('h1'):
        body = re.sub(r'(<h1[^>]*>).*?(</h1>)', lambda m: m.group(1) + ov['h1'] + m.group(2), body, count=1, flags=re.S)
    intro = ov.get('intro')
    if intro:
        html = ''.join(f'<p class="lead seo-intro">{p}</p>' for p in intro)
        m = re.search(r'</h1>(\s*<p[^>]*>.*?</p>)?', body, flags=re.S)
        if m:
            body = body[:m.end()] + html + body[m.end():]
    return body
